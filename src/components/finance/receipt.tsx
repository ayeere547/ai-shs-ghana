import { notFound } from "next/navigation";

import { cedis, METHOD_LABEL } from "@/lib/finance";
import { logoUrl } from "@/lib/school/settings";
import { createClient } from "@/lib/supabase/server";
import { formatDate } from "@/lib/utils";

import { PrintButton } from "./print-button";

type Payment = {
  id: string; amount: number; method: string; reference: string | null; receipt_number: string; received_at: string; status: string; school_id: string;
  students: { first_name: string; last_name: string; student_number: string };
  student_invoices: { invoice_number: string; total: number; amount_paid: number } | null;
};

/** Printable, school-branded receipt. RLS decides who can load it (finance staff, the child's guardians). */
export async function Receipt({ paymentId }: { paymentId: string }) {
  if (!/^[0-9a-f-]{36}$/i.test(paymentId)) notFound();
  const supabase = await createClient();
  const { data: p } = await supabase
    .from("student_payments")
    .select("id, amount, method, reference, receipt_number, received_at, status, school_id, students(first_name, last_name, student_number), student_invoices(invoice_number, total, amount_paid)")
    .eq("id", paymentId)
    .maybeSingle<Payment>();
  if (!p) notFound();
  const [{ data: school }, { data: branding }] = await Promise.all([
    supabase.from("schools").select("name, address, phone").eq("id", p.school_id).maybeSingle(),
    supabase.from("school_branding").select("primary_color, logo_path").eq("school_id", p.school_id).maybeSingle(),
  ]);
  const logo = logoUrl(branding?.logo_path);
  return (
    <div className="mx-auto max-w-xl rounded-lg border border-border bg-white p-8 text-[#111] print:border-0 print:p-0">
      <div className="flex items-center gap-4 border-b-4 pb-4" style={{ borderColor: branding?.primary_color ?? "#0b2545" }}>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        {logo && <img src={logo} alt="" className="h-14 w-14 object-contain" />}
        <div>
          <p className="text-lg font-bold">{school?.name ?? "School"}</p>
          {school && <p className="text-xs">{school.address} · {school.phone}</p>}
        </div>
      </div>
      <h1 className="mt-6 text-xl font-semibold">Official receipt {p.status === "reversed" && <span className="text-red-700">— REVERSED</span>}</h1>
      <dl className="mt-4 grid grid-cols-2 gap-y-2 text-sm">
        <dt className="text-gray-600">Receipt no.</dt><dd className="font-mono">{p.receipt_number}</dd>
        <dt className="text-gray-600">Date</dt><dd>{formatDate(p.received_at, { dateStyle: "long", timeStyle: "short" })}</dd>
        <dt className="text-gray-600">Received for</dt><dd>{p.students.first_name} {p.students.last_name} ({p.students.student_number})</dd>
        <dt className="text-gray-600">Amount</dt><dd className="text-lg font-bold">{cedis(p.amount)}</dd>
        <dt className="text-gray-600">Method</dt><dd>{METHOD_LABEL[p.method]}{p.reference ? ` · ${p.reference}` : ""}</dd>
        {p.student_invoices && (
          <>
            <dt className="text-gray-600">For invoice</dt><dd className="font-mono">{p.student_invoices.invoice_number}</dd>
            <dt className="text-gray-600">Balance now</dt><dd>{cedis(Math.max(0, Number(p.student_invoices.total) - Number(p.student_invoices.amount_paid)))}</dd>
          </>
        )}
      </dl>
      <p className="mt-8 text-xs text-gray-500">Generated by AI SHS Ghana for {school?.name ?? "the school"}.</p>
      <div className="mt-6 print:hidden"><PrintButton /></div>
    </div>
  );
}
